package com.ostentum.client;

import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import com.ostentum.entity.Dragonling;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.util.Mth;

/**
 * A quarter-scale ender dragon: neck, horned head with a jaw, back spines, two-part membrane wings, a three-part tail
 * and four legs. Generated by tools/dragonling_gen.py, which resamples every face from the vanilla dragon texture.
 */
public class DragonlingModel extends HierarchicalModel<Dragonling> {
    private final ModelPart body, neck, head, jaw, leftWing, leftWingTip, rightWing, rightWingTip, tail1, tail2, tail3;

    private final ModelPart root;

    public DragonlingModel(ModelPart root) {
        this.root = root;
        this.body = root.getChild("body");
        this.neck = this.body.getChild("neck");
        this.head = this.neck.getChild("head");
        this.jaw = this.head.getChild("jaw");
        this.leftWing = this.body.getChild("left_wing");
        this.leftWingTip = this.leftWing.getChild("left_wing_tip");
        this.rightWing = this.body.getChild("right_wing");
        this.rightWingTip = this.rightWing.getChild("right_wing_tip");
        this.tail1 = this.body.getChild("tail1");
        this.tail2 = this.tail1.getChild("tail2");
        this.tail3 = this.tail2.getChild("tail3");
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create()
                .texOffs(0, 0).addBox(-3.0F, 14.0F, -4.0F, 6, 5, 9)
                .texOffs(30, 0).addBox(-0.5F, 12.0F, -3.0F, 1, 2, 2)
                .texOffs(36, 0).addBox(-0.5F, 12.0F, 0.0F, 1, 2, 2)
                .texOffs(42, 0).addBox(-0.5F, 12.0F, 3.0F, 1, 2, 2)
                .texOffs(48, 0).addBox(1.5F, 19.0F, -3.0F, 2, 3, 2)
                .texOffs(56, 0).addBox(-3.5F, 19.0F, -3.0F, 2, 3, 2)
                .texOffs(64, 0).addBox(1.5F, 22.0F, -4.0F, 2, 1, 3)
                .texOffs(74, 0).addBox(-3.5F, 22.0F, -4.0F, 2, 1, 3)
                .texOffs(84, 0).addBox(1.0F, 18.0F, 2.0F, 3, 4, 3)
                .texOffs(96, 0).addBox(-4.0F, 18.0F, 2.0F, 3, 4, 3)
                .texOffs(108, 0).addBox(1.0F, 22.0F, 1.0F, 3, 1, 4)
                .texOffs(0, 14).addBox(-4.0F, 22.0F, 1.0F, 3, 1, 4),
            PartPose.offset(0.0F, 0.0F, 0.0F));
        PartDefinition neck = body.addOrReplaceChild("neck", CubeListBuilder.create()
                .texOffs(14, 14).addBox(-1.5F, -1.5F, -3.0F, 3, 3, 3)
                .texOffs(26, 14).addBox(-0.5F, -2.5F, -2.5F, 1, 1, 2),
            PartPose.offset(0.0F, 15.0F, -4.0F));
        PartDefinition head = neck.addOrReplaceChild("head", CubeListBuilder.create()
                .texOffs(32, 14).addBox(-3.5F, -5.0F, -6.0F, 7, 6, 6)
                .texOffs(58, 14).addBox(-2.5F, -1.0F, -10.0F, 5, 2, 4)
                .texOffs(76, 14).addBox(1.0F, -2.0F, -10.0F, 1, 1, 2)
                .texOffs(82, 14).addBox(-2.0F, -2.0F, -10.0F, 1, 1, 2)
                .texOffs(88, 14).addBox(1.5F, -7.0F, -4.0F, 1, 2, 3)
                .texOffs(96, 14).addBox(-2.5F, -7.0F, -4.0F, 1, 2, 3),
            PartPose.offset(0.0F, 0.0F, -3.0F));
        PartDefinition jaw = head.addOrReplaceChild("jaw", CubeListBuilder.create()
                .texOffs(104, 14).addBox(-2.5F, 0.0F, -4.0F, 5, 1, 4),
            PartPose.offset(0.0F, 1.0F, -6.0F));
        PartDefinition leftWing = body.addOrReplaceChild("left_wing", CubeListBuilder.create()
                .texOffs(0, 26).addBox(0.0F, -0.5F, -0.5F, 6, 1, 1)
                .texOffs(14, 26).addBox(0.0F, 0.0F, 0.0F, 6, 0, 6),
            PartPose.offset(3.0F, 14.0F, -2.0F));
        PartDefinition leftWingTip = leftWing.addOrReplaceChild("left_wing_tip", CubeListBuilder.create()
                .texOffs(38, 26).addBox(0.0F, -0.25F, -0.25F, 5, 1, 1)
                .texOffs(50, 26).addBox(0.0F, 0.0F, 0.0F, 5, 0, 6),
            PartPose.offset(6.0F, 0.0F, 0.0F));
        PartDefinition rightWing = body.addOrReplaceChild("right_wing", CubeListBuilder.create()
                .texOffs(72, 26).addBox(-6.0F, -0.5F, -0.5F, 6, 1, 1)
                .texOffs(86, 26).addBox(-6.0F, 0.0F, 0.0F, 6, 0, 6),
            PartPose.offset(-3.0F, 14.0F, -2.0F));
        PartDefinition rightWingTip = rightWing.addOrReplaceChild("right_wing_tip", CubeListBuilder.create()
                .texOffs(110, 26).addBox(-5.0F, -0.25F, -0.25F, 5, 1, 1)
                .texOffs(0, 32).addBox(-5.0F, 0.0F, 0.0F, 5, 0, 6),
            PartPose.offset(-6.0F, 0.0F, 0.0F));
        PartDefinition tail1 = body.addOrReplaceChild("tail1", CubeListBuilder.create()
                .texOffs(22, 32).addBox(-1.5F, -1.5F, 0.0F, 3, 3, 3)
                .texOffs(34, 32).addBox(-0.5F, -2.5F, 0.5F, 1, 1, 2),
            PartPose.offset(0.0F, 16.0F, 5.0F));
        PartDefinition tail2 = tail1.addOrReplaceChild("tail2", CubeListBuilder.create()
                .texOffs(40, 32).addBox(-1.0F, -1.0F, 0.0F, 2, 2, 3)
                .texOffs(50, 32).addBox(-0.5F, -2.0F, 0.5F, 1, 1, 2),
            PartPose.offset(0.0F, 0.0F, 3.0F));
        PartDefinition tail3 = tail2.addOrReplaceChild("tail3", CubeListBuilder.create()
                .texOffs(56, 32).addBox(-1.0F, -1.0F, 0.0F, 2, 2, 4),
            PartPose.offset(0.0F, 0.0F, 3.0F));
        return LayerDefinition.create(mesh, 128, 64);
    }

    @Override
    public ModelPart root() {
        return root;
    }

    @Override
    public void setupAnim(Dragonling entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        root.getAllParts().forEach(ModelPart::resetPose);
        float t = ageInTicks;
        this.body.y += Mth.sin(t * 0.15F) * 1.0F;
        this.head.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.6F;
        this.neck.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.4F;
        this.head.xRot = headPitch * Mth.DEG_TO_RAD;
        this.jaw.xRot = 0.15F + Mth.sin(t * 0.1F) * 0.1F;
        float flap = Mth.sin(t * 0.45F) * 0.6F;
        this.leftWing.zRot = flap;
        this.rightWing.zRot = -flap;
        this.leftWingTip.zRot = flap * 0.7F + 0.1F;
        this.rightWingTip.zRot = -flap * 0.7F - 0.1F;
        this.tail1.yRot = Mth.sin(t * 0.2F) * 0.2F;
        this.tail1.xRot = 0.15F;
        this.tail2.yRot = Mth.sin(t * 0.2F - 0.6F) * 0.25F;
        this.tail3.yRot = Mth.sin(t * 0.2F - 1.2F) * 0.3F;
    }
}
